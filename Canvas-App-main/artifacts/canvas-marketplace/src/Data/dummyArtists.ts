/**
 * Canvas — Luxury Beauty Directory (Hyderabad)
 * Dummy artist data for local development and UI prototyping.
 *
 * SCHEMA NOTES:
 * - `category` matches App.tsx's `discoverCategories` ids exactly (Bridal &
 *   Wedding / Party & Event Glam / Natural & Soft Aesthetics / Editorial &
 *   High Fashion / Specialized Skin & Grooming) and is what the "Discover"
 *   pills and the match/filter logic in App.tsx actually key off.
 * - `services` is the separate discipline taxonomy from HeroSearch.tsx
 *   (Makeup Artist / Hair Stylist / Nail Artist / Bridal Specialist /
 *   Editorial Look) — an artist can offer more than one.
 * - `city` and `location` hold the same value; App.tsx's distance filter
 *   reads `city`, other components may read `location`.
 * - `reviewCount`/`reviewsCount` and `bio`/`signature` are likewise
 *   duplicated under both spellings/lengths so whichever component reads
 *   which name still works. Worth consolidating to one name each once every
 *   consumer (ProfileModal included) is confirmed.
 * - `startingPrice` is a pre-formatted display string derived from the raw
 *   numeric `pricePerSession`.
 * - Images use Lorem Picsum (https://picsum.photos), seeded per artist, so
 *   every URL is guaranteed live and stable across reloads. Swap for a real
 *   CDN/Unsplash set whenever you have verified assets.
 */

